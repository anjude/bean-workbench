const { chromium } = require('playwright')
const assert = require('node:assert/strict')
const path = require('node:path')
const fs = require('node:fs')
;(async () => {
  const browser = await chromium.launch({ headless: true, executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome' })
  try {
    const page = await browser.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 1 })
    const errors = []; page.on('pageerror', e => errors.push(e.message))
    const root = path.join(__dirname, 'ui', 'stock-samples'); fs.mkdirSync(root, { recursive: true })
    await page.goto('http://127.0.0.1:5198/?still=1')
    await page.locator('.finance__cover-start').waitFor()
    assert.equal(await page.locator('.finance__cover-title').innerText(), '理财人格')
    assert(!await page.locator('.finance-preview-nav').innerText().then(text => text.includes('理财人格')))
    assert.equal(await page.locator('.finance__cover-illustration').evaluate(el => el.complete && el.naturalWidth > 0), true)
    await page.screenshot({ path: path.join(root, 'cover.png') })
    await page.locator('.finance__cover-start').click()
    for (let i = 1; i <= 4; i++) {
      await page.waitForFunction(id => window.__financePreview?.item.value?.id === id, `DEMO0${i}`)
      assert.equal(await page.locator('.finance__option').count(), 4)
      assert.equal(await page.locator('.finance__market').count(), 1)
      assert.equal(await page.locator('.finance__bubble').count(), 0)
      assert.equal(await page.locator('.finance__situation').count(), 1)
      if (i === 1) {
        assert.equal(await page.locator('.finance__sell-marker').innerText(), '你卖在这里')
        assert.equal(await page.locator('.finance__stock-line').evaluate(el => el.complete && el.naturalWidth > 0), true)
      }
      assert.equal(await page.getByText('不熟，换成日常题', { exact: true }).count(), 0)
      await page.screenshot({ path: path.join(root, `question-${i}.png`) })
      await page.locator('.finance__option').nth(i - 1).click()
    }
    await page.locator('.finance__result-title').waitFor()
    assert.equal(await page.locator('.finance__evidence').count(), 4)
    assert.equal(await page.locator('.finance__recap-goose').evaluate(el => el.complete && el.naturalWidth > 0), true)
    assert.equal(await page.locator('.finance__result-title').innerText(), '这四个瞬间')
    assert.equal(await page.locator('.finance__preview-poster').count(), 0)
    await page.screenshot({ path: path.join(root, 'summary.png') })
    await page.getByText('再选一次', { exact: true }).click()
    assert.equal(await page.evaluate(() => window.__financePreview.answers.value.length), 0)
    await page.evaluate(() => { const q = window.__financePreview; q.choose(q.item.value.options[0].id); q.pause() })
    await page.waitForTimeout(300)
    assert.equal(await page.evaluate(() => window.__financePreview.item.value.id), 'DEMO01')
    await page.evaluate(() => window.__financePreview.resume())
    await page.waitForFunction(() => window.__financePreview.item.value.id === 'DEMO02')
    for (const [width, theme] of [[320, 'light'], [390, 'dark']]) {
      await page.setViewportSize({ width, height: width === 320 ? 640 : 844 })
      for (let i = 1; i <= 4; i++) {
        await page.goto(`http://127.0.0.1:5198/?screen=DEMO0${i}&still=1&theme=${theme}`)
        await page.locator('.finance__market').waitFor()
        assert.equal(await page.locator('.finance__scroll').evaluate(el => el.scrollWidth > el.clientWidth), false)
        for (const box of await page.locator('.finance__option').evaluateAll(els => els.map(el => ({ width: el.clientWidth, scroll: el.scrollWidth })))) assert(box.scroll <= box.width + 1)
        for (const text of await page.locator('.finance__option').allTextContents()) assert(!/[。.!！]$/.test(text.trim()))
        await page.screenshot({ path: path.join(root, `question-${i}-${width}-${theme}.png`) })
      }
    }
    for (const [width, height, theme] of [[320, 640, 'light'], [390, 844, 'dark']]) {
      await page.setViewportSize({ width, height })
      await page.goto(`http://127.0.0.1:5198/?still=1&theme=${theme}`)
      await page.locator('.finance__cover-start').waitFor()
      assert.equal(await page.locator('.finance__scroll').evaluate(el => el.scrollWidth > el.clientWidth), false)
      await page.screenshot({ path: path.join(root, `cover-${width}-${theme}.png`) })
      await page.locator('.finance__cover-start').click()
      await page.waitForFunction(() => window.__financePreview.item.value?.id === 'DEMO01')
    }
    for (const [width, height, theme] of [[320, 640, 'light'], [390, 844, 'dark']]) {
      await page.setViewportSize({ width, height })
      await page.goto(`http://127.0.0.1:5198/?screen=result&still=1&theme=${theme}`)
      await page.locator('.finance__recap-list').waitFor()
      assert.equal(await page.locator('.finance__scroll').evaluate(el => el.scrollWidth > el.clientWidth), false)
      assert.equal(await page.locator('.finance__evidence').count(), 4)
      await page.screenshot({ path: path.join(root, `summary-${width}-${theme}.png`) })
    }
    await page.route('**/goose-reflection.svg', route => route.abort())
    await page.goto('http://127.0.0.1:5198/?screen=result&still=1')
    await page.locator('.finance__recap-goose').waitFor({ state: 'detached' })
    assert.equal(await page.locator('.finance__evidence').count(), 4)
    await page.route('**/cover-sofa.svg', route => route.abort())
    await page.goto('http://127.0.0.1:5198/?still=1')
    await page.locator('.finance__cover-placeholder').waitFor()
    await page.locator('.finance__cover-start').click()
    await page.waitForFunction(() => window.__financePreview.item.value?.id === 'DEMO01')
    await page.goto('http://127.0.0.1:5198/?screen=empty&still=1')
    assert.equal(await page.locator('.finance__evidence').count(), 4)
    assert.equal(await page.getByText('这题没有合适的选项，跳过了。', { exact: true }).count(), 4)
    assert.deepEqual(errors, [])
    console.log('PASS: 四题实际点选、关键行情与一句处境、无生活题、回看、重玩、后台恢复、全跳过、320px与深色、无页面错误')
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exit(1) })
