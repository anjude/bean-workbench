const { chromium } = require('playwright')
const assert = require('node:assert/strict')
const path = require('node:path')
const fs = require('node:fs')
const output = path.join(__dirname, 'ui'); fs.mkdirSync(output, { recursive: true })
;(async () => {
  const browser = await chromium.launch({ headless: true, executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome' })
  try {
    const context = await browser.newContext({ viewport: { width: 390, height: 844 } })
    const errors = []; context.on('page', p => p.on('pageerror', e => errors.push(e.message)))
    const a = await context.newPage()
    for (const key of ['A:goose-mirror', 'A:B:goose-mirror', 'A:C:goose-mirror']) {
      await a.request.post('http://127.0.0.1:5209/__redis', { data: JSON.stringify({ op: 'del', key }) })
    }
    const check = async page => {
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false)
      assert.equal(await page.locator('.mirror__option').evaluateAll(items => items.some(el => el.scrollWidth > el.clientWidth + 1)), false)
    }
    async function fill(page, offset, self = false) {
      for (let i = 0; i < 6; i++) {
        await page.locator('.mirror__option').nth((i + offset) % 4).click()
        if (i === 3) { await check(page); await page.screenshot({ path: path.join(output, self ? 'question-390-light.png' : 'question-320-dark.png'), fullPage: true }) }
        if (i < 5) await page.waitForFunction(n => document.querySelector('.mirror__progress-head')?.textContent.includes(`${n + 2} / 6`), i)
      }
    }
    await a.goto('http://127.0.0.1:5209/?user=A')
    await a.getByRole('button', { name: '先选我眼中的自己' }).waitFor()
    await a.screenshot({ path: path.join(output, 'intro-390-light.png'), fullPage: true }); await check(a)
    await a.getByRole('button', { name: '先选我眼中的自己' }).click(); await fill(a, 0, true)
    await a.getByRole('button', { name: '发给朋友选选看' }).waitFor()
    const share = await a.evaluate(() => window.__share())
    const query = share.path.split('?')[1]; assert(query.includes('key='))
    const b = await context.newPage(); await b.setViewportSize({ width: 320, height: 568 })
    await b.goto('http://127.0.0.1:5209/?user=B&theme=dark&' + query)
    await b.getByRole('button', { name: '选选我眼中的TA' }).click(); await fill(b, 1)
    await b.locator('.mirror__result').waitFor(); await check(b)
    assert.equal(await b.locator('.mirror__comparison').count(), 0)
    assert.equal(await b.locator('.mirror__highlight').count(), 0)
    await b.screenshot({ path: path.join(output, 'result-320-dark.png'), fullPage: true })
    const c = await context.newPage()
    await c.goto('http://127.0.0.1:5209/?user=C&' + query)
    await c.getByRole('button', { name: '选选我眼中的TA' }).click(); await fill(c, 2)
    await c.locator('.mirror__result').waitFor()
    await a.reload()
    await a.waitForFunction(() => document.querySelector('.mirror__records-entry')?.textContent.includes('2 人填写'))
    await a.screenshot({ path: path.join(output, 'waiting-390-light.png'), fullPage: true })
    await a.locator('.mirror__records-entry').click()
    await a.locator('.mirror__record').first().waitFor(); await a.waitForFunction(() => !document.querySelector('.mirror__record')?.disabled); assert.equal(await a.locator('.mirror__record').count(), 2)
    assert((await a.locator('.mirror__records').innerText()).includes('老朋友小陈'))
    assert((await a.locator('.mirror__records').innerText()).includes('朋友小林'))
    await check(a); await a.screenshot({ path: path.join(output, 'records-390-light.png'), fullPage: true })
    await a.locator('.mirror__record').first().click(); assert.equal(await a.locator('.mirror__comparison').count(), 6); assert.equal(await a.getByRole('button', { name: /看看每一题|收起每一题/ }).count(), 0)
    await a.screenshot({ path: path.join(output, 'result-390-light.png'), fullPage: true })
    await a.getByRole('button', { name: '返回填写记录', exact: true }).click()
    await a.getByRole('button', { name: '返回玩法首页', exact: true }).click()
    await a.locator('.mirror__records-entry').waitFor()
    await b.reload(); await b.getByRole('button', { name: '选选我眼中的TA' }).waitFor()
    const archive = await a.evaluate(() => JSON.parse(localStorage.getItem('gk.goose-atlas.v1')).find(r => r.projectId === 'goose-mirror'))
    assert.equal(archive.plays, 2); assert.equal(archive.mirrorResults.length, 2)
    await a.goto('http://127.0.0.1:5209/?user=A&surface=collection')
    const card = a.locator('.collection__card').filter({ hasText: '鹅眼中的我和我眼中的鹅' })
    await card.waitFor(); assert((await card.innerText()).includes('2 人填写'))
    await card.click(); await a.locator('.mirror__records-entry').waitFor()
    await a.setViewportSize({ width: 320, height: 568 })
    await a.goto('http://127.0.0.1:5209/?user=A&theme=dark')
    await a.locator('.mirror__records-entry').click(); await a.locator('.mirror__record').first().waitFor()
    await a.waitForFunction(() => !document.querySelector('.mirror__record')?.disabled)
    await check(a); await a.screenshot({ path: path.join(output, 'records-320-dark.png'), fullPage: true })
    assert.deepEqual(errors, [])
    console.log('PASS 真实Vue多人流程：B/C都提交→A收录两人→列表逐条六题→图鉴人数及跳首页→朋友刷新可再次填写；390浅色/320深色无溢出')
  } finally { await browser.close() }
})().catch(e => { console.error(e); process.exitCode = 1 })
